//! Sessions: an opaque token plus a per-request MAC.
//!
//! # Why a session exists at all
//!
//! It is a deviation, and it has one justification. A browser cannot hold an
//! ML-DSA signer, so a person at a page cannot sign each request. The session
//! stands in for an absent signer. It is not here because verification is
//! expensive; per-request verification is viable and is what agents do.
//!
//! # Why a token alone is not enough
//!
//! A bearer token is whatever the bearer holds. Steal the cookie, own the
//! session. That is the realistic attack on a working login and a plain token
//! has no answer to it.
//!
//! So a session is **two** things: an opaque token, and a 256-bit secret the
//! holder committed to inside the login signature. The browser keeps the
//! secret as a non-extractable key and MACs every request with it. The token
//! identifies the session; the MAC proves the sender is the party that opened
//! it.
//!
//! Symmetric throughout, deliberately. A MAC needs no signer, so this works
//! today without a browser PQC signer, and a 256-bit key is post-quantum
//! sound: Grover costs a square root, which leaves 128 bits of margin.
//!
//! # Why the verifier holding this key is not a backdoor
//!
//! It does hold one, and the distinction is worth stating rather than leaving
//! to judgement. A session secret is **not a secret held about a holder**; it
//! is a shared secret for a channel the verifier is one end of.
//!
//! Ask what an operator gains by having it. They can forge a MAC for a session
//! they already host, and they are the party checking that MAC. They could
//! equally decline to check it. A verifier can always let itself in, and that
//! is not a backdoor because there is nothing to back into.
//!
//! Identity key material is what the no-secrets rule exists to protect: it
//! would let an operator impersonate the holder **at other verifiers**, a
//! capability reaching beyond the relationship. A session secret reaches
//! nowhere — one session, one verifier, already the decision-maker.
//!
//! So this MAC protects a holder against a third party with a stolen cookie.
//! It was never protecting them against the verifier, and structurally cannot.
//!
//! # What a stolen database yields
//!
//! Nothing usable on its own. The store holds `SHAKE-256(token)`, never the
//! token, so an attacker with a dump cannot produce a token that looks up. It
//! does hold the session secret, because verifying a MAC requires the key —
//! but the secret alone does not identify a session without the token. The
//! two halves fail closed together: a cookie without the dump is inert, and
//! the dump without a cookie is inert.

use subtle::ConstantTimeEq;

use crate::error::{AuthError, StoreError};
use crate::proof::{shake256_32, AuthStrength};

/// An opaque session handle.
///
/// 256 bits of randomness and nothing else. Nothing about the actor, the
/// audience or the expiry is recoverable from it; it means something only to
/// a store that recognises it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SessionToken(Vec<u8>);

impl SessionToken {
    /// Wrap raw bytes generated by the caller's CSPRNG.
    ///
    /// The caller supplies the randomness so this crate needs no RNG
    /// dependency and cannot be the weak link in someone else's entropy.
    pub fn from_bytes(bytes: [u8; 32]) -> Self {
        SessionToken(bytes.to_vec())
    }

    /// Wrap a value received from a client, such as a cookie.
    ///
    /// Safe to call on untrusted input: a token grants nothing until a store
    /// recognises its hash, and guessing 256 random bits is infeasible.
    pub fn from_client_value(bytes: &[u8]) -> Self {
        SessionToken(bytes.to_vec())
    }

    /// The raw token bytes, for handing back to the client once.
    pub fn as_bytes(&self) -> &[u8] {
        &self.0
    }

    /// What the store actually holds. The token itself is never persisted.
    pub fn hash(&self) -> [u8; 32] {
        shake256_32(&self.0)
    }
}

/// The shared secret a session is bound to.
///
/// Committed to by the login signature, delivered to the holder exactly once,
/// and never retransmitted.
#[derive(Clone)]
pub struct SessionSecret([u8; 32]);

impl SessionSecret {
    /// Wrap 32 bytes from the caller's CSPRNG.
    pub fn from_bytes(bytes: [u8; 32]) -> Self {
        SessionSecret(bytes)
    }

    /// The commitment that goes in the login proof.
    pub fn commitment(&self) -> [u8; 32] {
        shake256_32(&self.0)
    }

    /// MAC over caller-supplied request bytes.
    ///
    /// **HMAC-SHA-256**, not SHAKE, despite SHAKE being this family's house
    /// hash everywhere else. The reason is a hard platform constraint rather
    /// than a preference.
    ///
    /// The browser holds this key as a **non-extractable** WebCrypto key, so
    /// only algorithms WebCrypto implements are available, and WebCrypto
    /// offers HMAC over SHA-2 with no SHA-3 or SHAKE. Computing a SHAKE MAC in
    /// JavaScript instead would mean JavaScript holding the raw key, which is
    /// precisely what a non-extractable key exists to prevent — and at that
    /// point the MAC adds nothing over a bearer token, because any XSS takes
    /// it.
    ///
    /// Still all-PQC: HMAC is symmetric, and Grover costs a square root, so a
    /// 256-bit key retains 128 bits. The commitment and the stored token hash
    /// remain SHAKE-256, since both run server-side where no such constraint
    /// applies.
    ///
    /// # The binding is the caller's responsibility, and it matters
    ///
    /// This crate MACs whatever bytes it is handed. It cannot know what a
    /// request is: HTTP method and path, a gRPC descriptor, a message id.
    ///
    /// **The binding must include something that differs per request** — a
    /// counter, a timestamp, a request id. A binding of method and path alone
    /// produces the same MAC every time, so anyone who observes one request
    /// can replay it for the life of the session. See
    /// `a_binding_without_a_varying_element_replays` in this module's tests,
    /// which demonstrates exactly that.
    pub fn mac(&self, binding: &[u8]) -> [u8; 32] {
        use hmac::Mac;
        // A 32-byte key is always a valid HMAC key length.
        let mut mac = hmac::Hmac::<sha2::Sha256>::new_from_slice(&self.0)
            .expect("HMAC accepts a key of any length");
        mac.update(binding);
        mac.finalize().into_bytes().into()
    }

    /// Constant-time MAC check.
    ///
    /// `==` on the digests would return as soon as two bytes differ, leaking
    /// how much of a guess was right and letting an attacker walk a forgery
    /// byte by byte.
    pub fn verify_mac(&self, binding: &[u8], presented: &[u8]) -> bool {
        let expected = self.mac(binding);
        expected.ct_eq(presented).into()
    }
}

impl core::fmt::Debug for SessionSecret {
    /// Never print the secret, including through a derived `Debug` on a
    /// containing type.
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str("SessionSecret(<redacted>)")
    }
}

/// A live session.
///
/// Generic over the relying party's actor type, so this crate carries none of
/// a consumer's domain types.
#[derive(Debug, Clone)]
pub struct Session<A> {
    /// What the store keys on. The token itself is not here.
    pub token_hash: [u8; 32],
    /// Whatever the relying party uses to name the account.
    pub actor: A,
    /// The relying party this session belongs to.
    pub audience: Vec<u8>,
    /// How the identity behind this session was established.
    pub strength: AuthStrength,
    /// Bumped to invalidate sessions in bulk without enumerating them.
    pub epoch: u64,
    /// Unix seconds the session was opened.
    pub issued_at: u64,
    /// Unix seconds the session stops being valid.
    pub expires_at: u64,
    /// When authority was last re-proven with a fresh ML-DSA signature.
    ///
    /// Separate from `strength` on purpose. `strength` says how the identity
    /// was established; this says how recently it was re-affirmed. A policy
    /// that wants "proven within the last five minutes" reads this, and
    /// nothing else can answer it.
    pub stepped_up_at: Option<u64>,
    secret: SessionSecret,
}

impl<A> Session<A> {
    /// Open a session bound to `token` and `secret`.
    pub fn new(
        token: &SessionToken,
        secret: SessionSecret,
        actor: A,
        audience: Vec<u8>,
        strength: AuthStrength,
        epoch: u64,
        issued_at: u64,
        expires_at: u64,
    ) -> Self {
        Session {
            token_hash: token.hash(),
            actor,
            audience,
            strength,
            epoch,
            issued_at,
            expires_at,
            stepped_up_at: None,
            secret,
        }
    }

    /// Whether `now` is at or past the expiry.
    pub fn is_expired(&self, now: u64) -> bool {
        now >= self.expires_at
    }

    /// Check a request's MAC against this session's secret.
    pub fn verify_mac(&self, binding: &[u8], presented: &[u8]) -> bool {
        self.secret.verify_mac(binding, presented)
    }
}

/// Where sessions live.
///
/// As with the nonce store, an in-process implementation is a test double: a
/// second instance of a service shares none of it.
pub trait SessionStore<A>: Send + Sync {
    /// Persist a newly opened session.
    fn create(&self, session: Session<A>) -> impl core::future::Future<Output = Result<(), StoreError>> + Send;

    /// Look up by the token's hash. The caller hashes; the store never sees a
    /// raw token and so cannot leak one.
    fn get(
        &self,
        token_hash: &[u8; 32],
    ) -> impl core::future::Future<Output = Result<Option<Session<A>>, StoreError>> + Send;

    /// Drop a session so its token stops working immediately.
    fn revoke(
        &self,
        token_hash: &[u8; 32],
    ) -> impl core::future::Future<Output = Result<(), StoreError>> + Send;
}

/// Validate a presented token and request MAC in one step.
///
/// Every failure returns [`AuthError::NoSuchSession`] or [`AuthError::BadMac`],
/// both of which carry the same outward message, so a caller cannot learn
/// whether a token existed, had expired, or simply had the wrong MAC.
pub async fn verify_session<A: Clone, S: SessionStore<A>>(
    store: &S,
    token: &SessionToken,
    binding: &[u8],
    presented_mac: &[u8],
    now: u64,
    current_epoch: u64,
) -> Result<Session<A>, AuthError> {
    let session = store
        .get(&token.hash())
        .await?
        .ok_or(AuthError::NoSuchSession)?;

    if session.is_expired(now) || session.epoch < current_epoch {
        return Err(AuthError::NoSuchSession);
    }

    if !session.verify_mac(binding, presented_mac) {
        return Err(AuthError::BadMac);
    }

    Ok(session)
}

/// In-process session store. Reference implementation, not a deployment.
pub struct InMemorySessionStore<A> {
    sessions: std::sync::Mutex<std::collections::HashMap<[u8; 32], Session<A>>>,
}

impl<A> Default for InMemorySessionStore<A> {
    fn default() -> Self {
        Self::new()
    }
}

impl<A> InMemorySessionStore<A> {
    /// An empty store.
    pub fn new() -> Self {
        Self {
            sessions: std::sync::Mutex::new(std::collections::HashMap::new()),
        }
    }
}

impl<A: Clone + Send + Sync> SessionStore<A> for InMemorySessionStore<A> {
    async fn create(&self, session: Session<A>) -> Result<(), StoreError> {
        self.sessions
            .lock()
            .expect("session store mutex poisoned")
            .insert(session.token_hash, session);
        Ok(())
    }

    async fn get(&self, token_hash: &[u8; 32]) -> Result<Option<Session<A>>, StoreError> {
        Ok(self
            .sessions
            .lock()
            .expect("session store mutex poisoned")
            .get(token_hash)
            .cloned())
    }

    async fn revoke(&self, token_hash: &[u8; 32]) -> Result<(), StoreError> {
        self.sessions
            .lock()
            .expect("session store mutex poisoned")
            .remove(token_hash);
        Ok(())
    }
}
